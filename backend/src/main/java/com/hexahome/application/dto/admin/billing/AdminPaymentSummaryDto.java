package com.hexahome.application.dto.admin.billing;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

public class AdminPaymentSummaryDto {

    private UUID id;
    private UUID userId;
    private String userName;
    private String maskedUserPhone;
    private UUID subscriptionId;
    private String orderId;
    private String paymentId;
    private String gateway;
    private BigDecimal amountInr;
    private String status;
    private Instant createdAt;

    public AdminPaymentSummaryDto() {
    }

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public UUID getUserId() {
        return userId;
    }

    public void setUserId(UUID userId) {
        this.userId = userId;
    }

    public String getUserName() {
        return userName;
    }

    public void setUserName(String userName) {
        this.userName = userName;
    }

    public String getMaskedUserPhone() {
        return maskedUserPhone;
    }

    public void setMaskedUserPhone(String maskedUserPhone) {
        this.maskedUserPhone = maskedUserPhone;
    }

    public UUID getSubscriptionId() {
        return subscriptionId;
    }

    public void setSubscriptionId(UUID subscriptionId) {
        this.subscriptionId = subscriptionId;
    }

    public String getOrderId() {
        return orderId;
    }

    public void setOrderId(String orderId) {
        this.orderId = orderId;
    }

    public String getPaymentId() {
        return paymentId;
    }

    public void setPaymentId(String paymentId) {
        this.paymentId = paymentId;
    }

    public String getGateway() {
        return gateway;
    }

    public void setGateway(String gateway) {
        this.gateway = gateway;
    }

    public BigDecimal getAmountInr() {
        return amountInr;
    }

    public void setAmountInr(BigDecimal amountInr) {
        this.amountInr = amountInr;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }
}
